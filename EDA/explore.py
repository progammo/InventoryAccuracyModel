def checkStock():
  results_df = test_df.copy()

  #Forecast from rolling 8 week mean
  results_df["forecast_demand_8wmean"] = results_df["rolling_8w_mean"]
  # print(results_df)

  # Forecast from LightGBM
  results_df["forecast_demand_LGBM"] = pred
  # print(results_df)
  # Safety stock (already computed previously)
  results_df = results_df.merge(
    df1[["sku_id", "q90_daily_demand"]].drop_duplicates("sku_id"),
    on="sku_id",
    how="left"
).rename(columns={"q90_daily_demand": "safety_stock"})

  # Expected stock after next week's demand
  results_df["expected_stock"] = (
      results_df["recorded_stock"] -
      results_df["forecast_demand_LGBM"]
  )

  # Quantity that should be ordered
  results_df["recommended_order"] = np.maximum(
      0,
      results_df["forecast_demand_LGBM"]
      + results_df["safety_stock"]
      - results_df["recorded_stock"]
  )

  # Inventory status
  conditions = [
      results_df["expected_stock"] < 0,
      results_df["expected_stock"] < results_df["safety_stock"]
  ]

  choices = [
      "Stockout",
      "Low Stock"
  ]

  results_df["status"] = np.select(
      conditions,
      choices,
      default="Safe"
  )
  results_df["overstock_limit"] = (
      results_df["forecast_demand_LGBM"] * 2
      + results_df["safety_stock"]
  )

  results_df.loc[
      results_df["recorded_stock"] > results_df["overstock_limit"],
      "status"
  ] = "Overstock"

  return results_df

