def find_iqr_outliers(df):
    # Aggregate total sales per SKU
    sku_sales = df.groupby("sku_id")["units_sold"].sum()

    Q1 = sku_sales.quantile(0.25)
    Q3 = sku_sales.quantile(0.75)
    IQR = Q3 - Q1

    # Define thresholds
    upper_bound = Q3 + 1.5 * IQR
    lower_bound = Q1 - 1.5 * IQR

    # Extract outliers
    high_outliers = sku_sales[sku_sales > upper_bound]
    low_outliers = sku_sales[sku_sales < lower_bound]

    # print(f"Upper Bound: {upper_bound:.2f}")
    # print(f"High-Volume Outliers: {len(high_outliers)} SKUs")
    # print(f"Low-Volume Outliers: {len(low_outliers)} SKUs")

    return high_outliers, low_outliers

