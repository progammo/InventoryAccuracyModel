def drawPlot(skuid, df):
    # 1. Filter for the specific SKU
    # Works whether sku_id is in a MultiIndex or a regular column
    if "sku_id" in df.index.names:
        subdf = df.xs(skuid, level="sku_id")
    else:
        subdf = df[df["sku_id"] == skuid]

    # Sort chronologically
    subdf = subdf.sort_values("date") if "date" in subdf.columns else subdf.sort_index()

    # 2. Extract x and y series directly from the filtered sub-dataframe
    x_dates = subdf["date"] if "date" in subdf.columns else subdf.index.get_level_values("date")
    y_sales = subdf["units_sold"]

    # 3. Render plot
    plt.figure(figsize=(10, 4))
